import {
  palette,
  reducedMotionDuration,
  scales,
  themes,
  TOKEN_PREFIX,
  type ColorValue,
  type Theme,
} from '../src/tokens/tokens.ts';

const p = TOKEN_PREFIX;

function decl(name: string, value: string): string {
  return `  ${name}: ${value};`;
}

function colorValue(value: ColorValue): string {
  if (typeof value === 'string') {
    const [name, step] = value.split('.') as [string, string];
    return `var(${p}-palette-${name}-${step})`;
  }
  return value.raw;
}

function themeBody(theme: Theme): string[] {
  return [
    decl('color-scheme', theme.colorScheme),
    ...Object.entries(theme.color).map(([role, value]) =>
      decl(`${p}-color-${role}`, colorValue(value)),
    ),
    ...Object.entries(theme.shadow).map(([name, value]) => decl(`${p}-shadow-${name}`, value)),
  ];
}

function block(selector: string, lines: string[], indent = ''): string {
  const body = lines.map((line) => indent + line).join('\n');
  return `${indent}${selector} {\n${body}\n${indent}}`;
}

export function renderTokensCss(): string {
  const primitives = Object.entries(palette).flatMap(([name, steps]) =>
    Object.entries(steps).map(([step, hex]) => decl(`${p}-palette-${name}-${step}`, hex)),
  );
  const scaleDecls = Object.entries(scales).flatMap(([group, values]) =>
    Object.entries(values).map(([name, value]) => decl(`${p}-${group}-${name}`, value)),
  );
  const durations = Object.keys(scales.motion)
    .filter((name) => name.startsWith('duration-'))
    .map((name) => decl(`${p}-motion-${name}`, reducedMotionDuration));

  return [
    '/* Generated by scripts/build-tokens.ts from src/tokens/tokens.ts. Do not edit by hand. */',
    '',
    block(':root', [...primitives, ...scaleDecls]),
    '',
    '/* Light is the default theme. */',
    block(":root,\n[data-theme='light']", themeBody(themes.light)),
    '',
    block("[data-theme='dark']", themeBody(themes.dark)),
    '',
    '/* With no explicit theme, follow the operating system. */',
    '@media (prefers-color-scheme: dark) {',
    block(":root:not([data-theme='light'])", themeBody(themes.dark), '  '),
    '}',
    '',
    '/* Every duration collapses (but stays above 0 so end events still fire). */',
    '@media (prefers-reduced-motion: reduce) {',
    block(':root', durations, '  '),
    '}',
    '',
  ].join('\n');
}
